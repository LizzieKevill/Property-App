import assert from 'node:assert/strict';
import {extractPhotos,enrichPhotos} from '../scripts/photos.mjs';
import {photoUrl} from '../site/gallery.mjs';
import {mergeCatalogue} from '../site/catalogue.mjs';
const otm='https://www.onthemarket.com/details/123/';
const photo='https://media.onthemarket.com/properties/123/456/image-0-1024x1024.jpg';
const otmHtml='<script id="__NEXT_DATA__" type="application/json">'+JSON.stringify({props:{pageProps:{initialReduxState:{property:{images:[{largeUrl:photo,text:'Front of house'},{largeUrl:photo},{largeUrl:'https://media.onthemarket.com/properties/999/456/image-0.jpg'},{largeUrl:'https://evil.example/image.jpg'}]}}}}})+'</script>';
assert.deepEqual(extractPhotos(otmHtml,otm),[{url:photo,caption:'Front of house'}]);
assert.equal(extractPhotos('<html>Access denied</html>',otm).length,0);
assert.equal(extractPhotos(otmHtml,'https://example.com/details/123/').length,0);
assert.equal(photoUrl('javascript:alert(1)'), '');
assert.equal(photoUrl('https://media.onthemarket.com.evil.example/properties/123/image.jpg'), '');
assert.equal(photoUrl('https://user:pass@media.onthemarket.com/properties/123/image.jpg'), '');
const rightPhoto='https://media.rightmove.co.uk/property-photo/hash/456/photo.jpeg';
const refs=[{propertyData:1},{id:2,images:3},456,[4],{url:5,caption:6},rightPhoto,'Garden'];
const rightHtml='window.__PAGE_MODEL = '+JSON.stringify({data:JSON.stringify(refs)})+';';
assert.deepEqual(extractPhotos(rightHtml,'https://www.rightmove.co.uk/properties/456'),[{url:rightPhoto,caption:'Garden'}]);
assert.equal(extractPhotos(rightHtml,'https://www.rightmove.co.uk/properties/999').length,0);
const landPhoto='https://img.landsale.co.uk/images/properties/photo.jpeg';
const land='https://www.landsale.co.uk/properties/789';
const landHtml='<script type="application/ld+json">'+JSON.stringify({'@graph':[{'@type':'Organization',image:'https://example.com/logo.png'},{'@type':'RealEstateListing',image:[landPhoto,landPhoto]}]})+'</script>';
assert.deepEqual(extractPhotos(landHtml,land),[{url:landPhoto,caption:''}]);
const now='2026-10-11T20:00:00Z';
const p={id:'real-test',url:otm,links:[{source:'LandSale',url:land}],seen:true,decision:'Liked',notes:'Keep this',folders:['f'],history:[],created:1,observedAt:'2026-10-10'};
let calls=0;
const data=await enrichPhotos({properties:[structuredClone(p)]},{now,fetchPage:async(url)=>{calls++;return {ok:url===land,text:async()=>landHtml};}});
assert.equal(calls,2);
assert.equal(data.properties[0].photos.length,1);
assert.equal(data.properties[0].photosSourceUrl,land);
await enrichPhotos(data,{now,fetchPage:async()=>{throw Error('Should not fetch a fresh gallery');}});
assert.equal(data.properties[0].photosChecked,now);
await enrichPhotos(data,{force:true,now:'2026-10-12',fetchPage:async()=>{throw Error('Unavailable');}});
assert.equal(data.properties[0].photos[0].url,landPhoto);
const merged=mergeCatalogue([p],data.properties)[0];
assert.equal(merged.photos.length,1); // Photos update even when the listing observation date is unchanged.
assert.equal(merged.notes,'Keep this');
assert.equal(merged.decision,'Liked');
assert.deepEqual(merged.folders,['f']);
console.log('18 photo extraction, refresh, and merge assertions passed.');
